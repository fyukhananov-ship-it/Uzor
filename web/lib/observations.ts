/**
 * Простая стабильная хэш-функция (FNV-1a 32-bit).
 * Используется только для выбора варианта шаблона — без криптографических требований.
 */
function fnv1a(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

function pick<T>(arr: T[], seed: number): T {
  if (arr.length === 0) {
    throw new Error("empty_template_set");
  }
  return arr[seed % arr.length];
}

/**
 * Сборка трёх наблюдений для пары. Стабильна для одинакового входа.
 */
export function buildObservations(
  birthDateUser: string,
  birthDatePartner: string,
  context: PairContext,
): Observation[] {
  const seed = fnv1a(
    `${birthDateUser}|${birthDatePartner}|${context.friction}|${context.user.personalDay}|${context.partner.personalDay}`,
  );

  const dynamic = pick(DYNAMIC_BY_FRICTION[context.friction], seed);
  const friction = pick(FRICTION_BY_ZONE[context.friction], (seed >>> 8) >>> 0);
  const strength = pick(STRENGTH_BY_ZONE[context.friction], (seed >>> 16) >>> 0);

  return [
    { kind: "dynamic", text: dynamic },
    { kind: "friction", text: friction },
    { kind: "strength", text: strength },
  ];
}
